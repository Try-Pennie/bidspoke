import { readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { REPO_ROOT } from './_scan-utils'

/**
 * The coverage floors in CI must equal what the specs actually declare (#797).
 *
 * The checker itself takes a MINIMUM rather than an equality, deliberately:
 * adding a page should not fail the gate in CI until somebody remembers to bump
 * a number, because a number that has to be bumped reflexively stops being read.
 *
 * But a minimum has its own failure. Set it once and forget it, and the gate
 * happily tolerates losing pages: nine of ten scanned still clears a floor of
 * five, and nothing says so. That is the same silence the floor was added to
 * remove, moved one step back.
 *
 * So the floor is kept exactly right HERE, where the failure is local, instant
 * and explains itself, rather than in CI where it would be a red build on an
 * unrelated PR. It is derived from the specs rather than remembered beside them
 * (LESSONS L41), so the two cannot drift.
 */
const CI = path.join(REPO_ROOT, '.github/workflows/ci.yml')

const read = (relative: string): string => {
  const file = path.join(REPO_ROOT, relative)
  const text = readFileSync(file, 'utf8')
  expect(text.length, `${file} is empty`).toBeGreaterThan(0)
  return text
}

/** The floor passed to the coverage checker for a given report name. */
function floorFor(reportName: string): number {
  const line = read('.github/workflows/ci.yml')
    .split('\n')
    .find((l) => l.includes('playwright-coverage.mjs') && l.includes(reportName))
  expect(line, `no coverage check found for ${reportName} in ${CI}`).toBeDefined()
  const match = line!.match(/([0-9]+)\s*$/)
  expect(match, `the coverage check for ${reportName} passes no floor`).not.toBeNull()
  return Number(match![1])
}

/**
 * Entries in a `const NAME = [ ... ]` array. Tolerates a type annotation between
 * the name and the `=`, because one of the two lists carries one and a matcher
 * that knew only the other shape would have failed on the day it was written.
 */
function arrayLength(src: string, name: string): number {
  const declaration = new RegExp(`const ${name}(?::[^=]+)? = \\[`)
  const match = declaration.exec(src)
  expect(match, `${name} not found`).not.toBeNull()
  const start = match!.index
  const body = src.slice(start, src.indexOf('\n]', start))
  // Count entries, not lines, and ignore anything inside a comment.
  const entries = body
    .split('\n')
    .slice(1)
    .filter((l) => !/^\s*(\/\/|\/\*|\*)/.test(l))
    .filter((l) => /^\s*['{]/.test(l))
  expect(entries.length, `${name} appears to be empty`).toBeGreaterThan(0)
  return entries.length
}

/** Top-level `test('...')` calls, which are the ones not generated by a loop. */
const standaloneTests = (src: string): number => (src.match(/^ {2}test\(/gm) ?? []).length

describe('the accessibility coverage floor matches the pages it declares (#797)', () => {
  it('equals the page list plus the standalone login test', () => {
    const spec = read('apps/web/e2e/a11y.spec.ts')
    const expected = arrayLength(spec, 'PAGES') + standaloneTests(spec)
    expect(
      floorFor('a11y-report.json'),
      `the accessibility spec declares ${expected} tests. Update the floor in ci.yml to match, so the gate cannot quietly cover fewer pages than it lists.`,
    ).toBe(expected)
  })
})

describe('the auth gate coverage floor matches the paths it declares (#797)', () => {
  it('equals the gated paths, the public paths, and the standalone tests', () => {
    const probe = read('apps/web/e2e/auth-gate.probe.ts')
    const expected =
      arrayLength(probe, 'GATED_PATHS') + arrayLength(probe, 'PUBLIC_PATHS') + standaloneTests(probe)
    expect(
      floorFor('gate-report.json'),
      `the auth gate probe declares ${expected} tests. Update the floor in ci.yml to match, so the gate cannot quietly probe fewer paths than it lists.`,
    ).toBe(expected)
  })
})

describe('both gates actually run the checker (#797)', () => {
  it('writes a JSON report and then checks it, in both jobs', () => {
    // The checker reading a report nobody wrote is the shape it is built to
    // refuse, but a job that never invokes it at all is quieter still.
    const ci = read('.github/workflows/ci.yml')
    for (const report of ['a11y-report.json', 'gate-report.json']) {
      expect(ci, `${report} is never produced`).toContain(`PLAYWRIGHT_JSON_OUTPUT_NAME`)
      expect(ci, `${report} is never checked`).toContain(`playwright-coverage.mjs "\${{ runner.temp }}/${report}"`)
    }
    // And the run that produces it must actually ask for the json reporter.
    const jsonRuns = ci.split('\n').filter((l) => l.includes('--reporter=json'))
    expect(jsonRuns.length, 'a job writes no JSON report, so its checker has nothing to read').toBe(2)
  })
})
